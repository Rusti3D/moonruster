#!/usr/bin/env python3
# Merges the dynamic trace (tracer.py JSON lines) and the static scan
# (static_scan.py JSON) into the Moonraker surface the corpus components use,
# as markdown (docs/PLUGINS.md Phase 0).
# usage: summarize.py TRACE.jsonl STATIC.json > surface.md
import json
import sys
from collections import defaultdict


def short(mod):
    return mod.rsplit(".", 1)[-1]


def main():
    uses = defaultdict(lambda: defaultdict(set))   # owner -> attr -> {component (op)}
    back = defaultdict(lambda: defaultdict(set))   # component class -> attr -> {moonraker module}
    calls = defaultdict(set)                       # name -> {args}
    for line in open(sys.argv[1]):
        r = json.loads(line)
        if r["kind"] == "use":
            tag = short(r["by"]) + ("" if r["op"] == "get" else " (set)")
            uses[r["owner"]][r["name"]].add(tag)
        elif r["kind"] == "back":
            back[r["owner"]][r["name"]].add(short(r["by"]))
        elif r["kind"] == "call":
            calls[r["name"]].add(" ".join(r["args"]))
    static = json.load(open(sys.argv[2]))
    st = defaultdict(lambda: defaultdict(set))
    for path, s in static.items():
        comp = path.rsplit("/", 1)[-1][:-3]
        for name in s["server"]:
            st["moonraker.server.Server"][name].add(comp)
        for name in s["config"]:
            st["moonraker.confighelper.ConfigHelper"][name].add(comp)
        for c, names in s["components"].items():
            for name in names:
                st[f"component {c}"][name].add(comp)
        for m, names in s["modules"].items():
            for name in names:
                st[m][name].add(comp)
        for m, names in s["imports"].items():
            for name in names:
                st[m][f"import {name}"].add(comp)
        for w in s["writes"]:
            st["writes"][w].add(comp)
        for sc in s["subclasses"]:
            st["subclasses"][sc].add(comp)

    print("# Moonraker surface used by the corpus components\n")
    print("Generated by `tools/plugin_trace/summarize.py` from the dynamic trace (run_trace.sh +")
    print("exercise.py, both variants) and the static scan (static_scan.py). Entries name the components")
    print("that use them; `(set)` marks a write.\n")
    print("## Dynamic: components reading or writing Moonraker objects\n")
    for owner in sorted(uses):
        print(f"### `{owner}`\n")
        for attr in sorted(uses[owner]):
            print(f"- `{attr}`: {', '.join(sorted(uses[owner][attr]))}")
        print()
    print("## Dynamic: what Moonraker reads from component objects\n")
    for owner in sorted(back):
        print(f"### `{owner}`\n")
        for attr in sorted(back[owner]):
            print(f"- `{attr}` (by {', '.join(sorted(back[owner][attr]))})")
        print()
    print("## Dynamic: registration and lookup calls\n")
    for name in sorted(calls):
        print(f"- `{name}`: {', '.join(f'`{a}`' for a in sorted(calls[name]) if a)}")
    print("\n## Static: all code paths, by receiver\n")
    for owner in sorted(st):
        print(f"### `{owner}`\n")
        for attr in sorted(st[owner]):
            print(f"- `{attr}`: {', '.join(sorted(st[owner][attr]))}")
        print()


if __name__ == "__main__":
    main()

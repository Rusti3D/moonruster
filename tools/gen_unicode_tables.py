#!/usr/bin/env python3
# Unicode tables for crates/pycompat/src/pyfmt.rs from CPython's own unicode database (the
# reference Moonraker runs on): code points str.isprintable() rejects (repr()
# escapes them), Unicode decimal digits (int() / float() accept them) and
# str.isspace() whitespace (int() / float() strip it).
#   python3 tools/gen_unicode_tables.py > crates/pycompat/src/pyfmt_tables.rs
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(cp)
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, rs):
    body = ", ".join(f"(0x{a:X}, 0x{b:X})" for a, b in rs)
    return f"pub static {name}: &[(u32, u32)] = &[{body}];\n"


def main():
    nonprint = ranges(lambda cp: not chr(cp).isprintable())
    space = ranges(lambda cp: chr(cp).isspace())
    # decimal digits: the code point of each block's zero (digits are
    # contiguous 0..9 in every Nd block)
    zeros = [cp for cp in range(0x110000) if unicodedata.decimal(chr(cp), None) == 0]
    assert all(unicodedata.decimal(chr(z + d), None) == d for z in zeros for d in range(10))
    sys.stdout.write(
        f"// Generated by tools/gen_unicode_tables.py from CPython {sys.version.split()[0]} "
        f"(Unicode {unicodedata.unidata_version}): do not edit\n\n"
        "/// code points str.isprintable() rejects: repr() escapes them\n" + table("NONPRINTABLE", nonprint) + "\n"
        "/// str.isspace() whitespace: int() / float() strip it\n" + table("WHITESPACE", space) + "\n"
        "/// the zero of each decimal digit block: int() / float() accept its digits\n"
        f"pub static DIGIT_ZEROS: &[u32] = &[{', '.join(f'0x{z:X}' for z in zeros)}];\n"
    )


if __name__ == "__main__":
    main()

def png(w, h, rgb=(200, 30, 90)):
    raw = b"".join(b"\x00" + bytes(rgb) * w for _ in range(h))
    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)
    return (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
            + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))

def thumb_block(w, h, tag="thumbnail", ext=None):
    data = base64.b64encode(png(w, h)).decode()
    lines = [data[i:i + 78] for i in range(0, len(data), 78)]
    out = [f"; {tag} begin {w}x{h} {len(data)}"]
    out += [f"; {ln}" for ln in lines]
    out.append(f"; {tag} end")
    return "\n".join(out) + "\n"

def moves(layers=5, lh=0.2, first=0.2, zfmt="G1 Z{z:.3f} F720"):
    out = []
    z = first
    for i in range(layers):
        out.append(zfmt.format(z=z))
        out.append(f"G1 X{10 + i} Y10 E0.5 F1200")
        out.append("G1 X20 Y20 E1.0")
        z += lh
    return "\n".join(out) + "\n"


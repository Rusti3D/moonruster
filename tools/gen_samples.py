def ufp(prefix="/"):
    # Cura stores member names with a leading slash
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        zf.writestr(prefix + "3D/model.gcode", SAMPLES["cura.gcode"])
        zf.writestr(prefix + "Metadata/thumbnail.png", png(64, 48))
        zf.writestr(prefix + "[Content_Types].xml", "<x/>")
    return buf.getvalue()

def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    for name, data in SAMPLES.items():
        with open(os.path.join(out, name), "w", newline="") as f:
            f.write(data)
    with open(os.path.join(out, "cura_pkg.ufp"), "wb") as f:
        f.write(ufp())
    with open(os.path.join(out, "bad_pkg.ufp"), "wb") as f:
        f.write(ufp(prefix=""))

if __name__ == "__main__":
    main()
